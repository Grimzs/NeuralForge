    let lang = 'ru';
    try {
        const saved = localStorage.getItem(KEY);
        if (saved && dicts[saved]) lang = saved;
    } catch (e) { }

    function fmt(s, params) {
        if (!params) return s;
        return String(s).replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : m));
    }

    function t(key, params) {
        let s = key;
        if (dicts[lang] && dicts[lang][key] != null) s = dicts[lang][key];
        else if (dicts.ru[key] != null) s = dicts.ru[key];
        return fmt(s, params);
    }

    function apply(root) {
        const r = root || document;
        r.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
        r.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
        r.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.getAttribute('data-i18n-ph')); });
        r.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.getAttribute('data-i18n-title')); });
        r.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
    }

    function setLang(l) {
        lang = dicts[l] ? l : 'ru';
        try { localStorage.setItem(KEY, lang); } catch (e) { }
        document.documentElement.lang = lang;
        apply(document);
        window.dispatchEvent(new CustomEvent('langchange', { detail: { lang: lang } }));
    }

    function getLang() { return lang; }
    function toggle() { setLang(lang === 'ru' ? 'en' : 'ru'); }

    document.documentElement.lang = lang;
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', () => apply(document));
    } else {
        apply(document);
    }

    return { t: t, apply: apply, setLang: setLang, getLang: getLang, toggle: toggle, dicts: dicts };
